# -*- coding: utf-8 -*-
from django.conf import settings
from django.db import models
from django.utils.translation import gettext_lazy as _


class VisitSummary(models.Model):
    """
    An immutable, point-in-time summary of one child's records over a date
    range.

    Everything needed to render the summary (statistics, full record details,
    the child's name and birth date, the generator's timezone) is captured in
    ``data`` at creation time. Later edits and deletions of the underlying
    care entries never reach a saved summary: opening it shows exactly what
    was shown to the doctor. Rows are created in a single transaction and
    have no edit path in the application.
    """

    child = models.ForeignKey(
        "core.Child",
        on_delete=models.CASCADE,
        related_name="visit_summaries",
        verbose_name=_("Child"),
    )
    title = models.CharField(
        max_length=255,
        blank=True,
        verbose_name=_("Title"),
        help_text=_("Optional label, e.g. the reason for the visit."),
    )
    start_date = models.DateField(verbose_name=_("Start date"))
    end_date = models.DateField(verbose_name=_("End date"))
    generated_at = models.DateTimeField(
        auto_now_add=True, db_index=True, verbose_name=_("Generated at")
    )
    generated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        blank=True,
        null=True,
        verbose_name=_("Generated by"),
    )
    data = models.JSONField(verbose_name=_("Snapshot data"))

    class Meta:
        default_permissions = ("view", "add", "change", "delete")
        ordering = ["-generated_at"]
        verbose_name = _("Visit summary")
        verbose_name_plural = _("Visit summaries")

    def __str__(self):
        if self.title:
            return self.title
        return _("Visit summary %(start)s to %(end)s") % {
            "start": self.start_date,
            "end": self.end_date,
        }

    @property
    def total_entries(self):
        """Total number of frozen records across all sections."""
        counts = self.data.get("counts", {}) if self.data else {}
        return sum(counts.values())
